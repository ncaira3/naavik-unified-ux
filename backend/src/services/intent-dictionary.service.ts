export class IntentDictionaryService {
  /**
   * Match a user message against the intent dictionary.
   * Returns the first matching intent and a confidence score.
   */
  static classify(message: string): { intent: NaavikIntent; confidence: number } {
    const lower = message.toLowerCase();

    for (const entry of INTENT_DICTIONARY) {
      for (const phrase of entry.phrases) {
        if (lower.includes(phrase)) {
          return { intent: entry.intent, confidence: 0.95 };
        }
      }
    }

    return { intent: 'unmatched', confidence: 0 };
  }

  /**
   * Get all phrases for a given intent (useful for testing / export).
   */
  static getPhrasesForIntent(intent: NaavikIntent): string[] {
    const entry = INTENT_DICTIONARY.find((e) => e.intent === intent);
    return entry?.phrases ?? [];
  }

  /**
   * Return the full dictionary (useful for front-end consumption).
   */
  static getDictionary(): IntentEntry[] {
    return INTENT_DICTIONARY;
  }
}
